#!/bin/bash

# Deterministic root README assembly from engineer-approved Xoch packets.

set -euo pipefail

usage() {
  cat <<'EOF'
Usage:
  readme-actions.sh assemble [options] [packet.md ...]

Options:
  --root ROOT         Project root. Default: current directory.
  --manifest FILE     JSON manifest containing title, output, and ordered packets.
  --output FILE       README output path, relative to root. Default: README.md.
  --title TITLE       Top-level README title.
  --stdout            Print assembled markdown instead of writing it.
  --dry-run           Validate and report the assembly without writing.
  -h, --help          Show this help.

Manifest shape:
  {
    "title": "Project Name",
    "output": "README.md",
    "packets": [
      ".xoch/docs/OVERVIEW.md",
      {"path": ".xoch/docs/SETUP.md", "enabled": true}
    ]
  }
EOF
}

command="${1:-}"
[ -n "$command" ] || { usage; exit 2; }
[ "$command" = "assemble" ] || { usage >&2; echo "Unknown command: $command" >&2; exit 2; }
shift

root="."
manifest=""
output="README.md"
title=""
stdout_mode="false"
dry_run="false"
packets=()

while [ "$#" -gt 0 ]; do
  case "$1" in
    --root) root="$2"; shift 2 ;;
    --manifest) manifest="$2"; shift 2 ;;
    --output) output="$2"; shift 2 ;;
    --title) title="$2"; shift 2 ;;
    --stdout) stdout_mode="true"; shift ;;
    --dry-run) dry_run="true"; shift ;;
    -h|--help) usage; exit 0 ;;
    --) shift; while [ "$#" -gt 0 ]; do packets+=("$1"); shift; done ;;
    -*) echo "Unknown option: $1" >&2; usage >&2; exit 2 ;;
    *) packets+=("$1"); shift ;;
  esac
done

set +u
ruby -rjson -rfileutils - "$root" "$manifest" "$output" "$title" "$stdout_mode" "$dry_run" "${packets[@]}" <<'RUBY'
root, manifest, output, title, stdout_mode, dry_run, *cli_packets = ARGV
root = File.expand_path(root)
abort("Project root not found: #{root}") unless Dir.exist?(root)

def within_root(root, path)
  expanded = File.expand_path(path, root)
  return expanded if expanded == root || expanded.start_with?(root + File::SEPARATOR)
  abort("Path escapes project root: #{path}")
end

packet_paths = cli_packets
unless manifest.empty?
  manifest_path = within_root(root, manifest)
  abort("Manifest not found: #{manifest_path}") unless File.file?(manifest_path)
  data = JSON.parse(File.read(manifest_path))
  title = data["title"].to_s if title.empty? && data["title"]
  output = data["output"].to_s if output == "README.md" && data["output"]
  packet_paths = Array(data["packets"]).each_with_object([]) do |entry, selected|
    if entry.is_a?(String)
      selected << entry
    elsif entry.is_a?(Hash) && entry.fetch("enabled", true)
      selected << entry["path"] if entry["path"]
    end
  end
end

abort("No README packets provided") if packet_paths.empty?
title = File.basename(root) if title.empty?
resolved = packet_paths.map do |path|
  expanded = within_root(root, path)
  abort("Packet not found: #{expanded}") unless File.file?(expanded)
  abort("Packet must be markdown: #{path}") unless File.extname(expanded).downcase == ".md"
  [path, expanded]
end

output_path = within_root(root, output)
lines = []
lines << "# #{title}"
lines << ""
lines << "<!-- Generated by Xoch from ordered README packets. Edit packets, then rebuild. -->"
resolved.each do |display_path, expanded|
  body = File.read(expanded).strip
  lines << ""
  lines << "<!-- XOCH PACKET: #{display_path} -->"
  lines << body
  lines << "<!-- END XOCH PACKET: #{display_path} -->"
end
rendered = lines.join("\n") + "\n"

if dry_run == "true"
  puts "README assembly valid"
  puts "Output: #{output_path}"
  puts "Title: #{title}"
  resolved.each_with_index { |(path, _), index| puts "#{index + 1}. #{path}" }
elsif stdout_mode == "true"
  print rendered
else
  FileUtils.mkdir_p(File.dirname(output_path))
  temp = "#{output_path}.xoch-tmp"
  File.write(temp, rendered)
  File.rename(temp, output_path)
  puts "README assembled: #{output_path} (#{resolved.length} packets)"
end
RUBY
status=$?
set -u
exit "$status"
