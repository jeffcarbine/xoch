#!/usr/bin/env node
'use strict';

// Deterministic root README assembly from engineer-approved Xoch packets.

const fs = require('fs');
const path = require('path');

function usage() {
  console.log('Usage:');
  console.log('  readme-actions.js assemble [options] [packet.md ...]');
  console.log('');
  console.log('Options:');
  console.log('  --root ROOT         Project root. Default: current directory.');
  console.log('  --manifest FILE     JSON manifest containing title, output, and ordered packets.');
  console.log('  --output FILE       README output path, relative to root. Default: README.md.');
  console.log('  --title TITLE       Top-level README title.');
  console.log('  --stdout            Print assembled markdown instead of writing it.');
  console.log('  --dry-run           Validate and report the assembly without writing.');
  console.log('  -h, --help          Show this help.');
  console.log('');
  console.log('Manifest shape:');
  console.log('  {');
  console.log('    "title": "Project Name",');
  console.log('    "output": "README.md",');
  console.log('    "packets": [');
  console.log('      ".xoch/docs/OVERVIEW.md",');
  console.log('      {"path": ".xoch/docs/SETUP.md", "enabled": true}');
  console.log('    ]');
  console.log('  }');
}

function parseArgs(argv) {
  const flags = { root: '.', manifest: '', output: 'README.md', title: '', stdoutMode: false, dryRun: false };
  const packets = [];
  let i = 0;
  while (i < argv.length) {
    const arg = argv[i];
    if (arg === '--root') { flags.root = argv[i + 1]; i += 2; }
    else if (arg === '--manifest') { flags.manifest = argv[i + 1]; i += 2; }
    else if (arg === '--output') { flags.output = argv[i + 1]; i += 2; }
    else if (arg === '--title') { flags.title = argv[i + 1]; i += 2; }
    else if (arg === '--stdout') { flags.stdoutMode = true; i += 1; }
    else if (arg === '--dry-run') { flags.dryRun = true; i += 1; }
    else if (arg === '-h' || arg === '--help') { usage(); process.exit(0); }
    else if (arg === '--') {
      i += 1;
      while (i < argv.length) { packets.push(argv[i]); i += 1; }
    } else if (arg.startsWith('-')) {
      console.error(`Unknown option: ${arg}`);
      usage();
      process.exit(2);
    } else {
      packets.push(arg);
      i += 1;
    }
  }
  return { flags, packets };
}

function withinRoot(root, candidate) {
  const expanded = path.resolve(root, candidate);
  if (expanded === root || expanded.startsWith(`${root}${path.sep}`)) return expanded;
  console.error(`Path escapes project root: ${candidate}`);
  process.exit(1);
  return null;
}

function assemble(argv) {
  const { flags, packets: cliPackets } = parseArgs(argv);
  const root = path.resolve(flags.root);
  let { manifest, output, title } = flags;
  const { stdoutMode, dryRun } = flags;

  if (!fs.existsSync(root) || !fs.statSync(root).isDirectory()) {
    console.error(`Project root not found: ${root}`);
    process.exit(1);
  }

  let packetPaths = cliPackets;
  if (manifest) {
    const manifestPath = withinRoot(root, manifest);
    if (!fs.existsSync(manifestPath)) {
      console.error(`Manifest not found: ${manifestPath}`);
      process.exit(1);
    }
    const data = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
    if (!title && data.title) title = String(data.title);
    if (output === 'README.md' && data.output) output = String(data.output);
    packetPaths = [];
    for (const entry of data.packets || []) {
      if (typeof entry === 'string') packetPaths.push(entry);
      else if (entry && typeof entry === 'object' && (entry.enabled ?? true) && entry.path) packetPaths.push(entry.path);
    }
  }

  if (packetPaths.length === 0) {
    console.error('No README packets provided');
    process.exit(1);
  }
  if (!title) title = path.basename(root);

  const resolved = packetPaths.map((p) => {
    const expanded = withinRoot(root, p);
    if (!fs.existsSync(expanded) || !fs.statSync(expanded).isFile()) {
      console.error(`Packet not found: ${expanded}`);
      process.exit(1);
    }
    if (path.extname(expanded).toLowerCase() !== '.md') {
      console.error(`Packet must be markdown: ${p}`);
      process.exit(1);
    }
    return [p, expanded];
  });

  const outputPath = withinRoot(root, output);
  const lines = [`# ${title}`, ''];
  lines.push('<!-- Generated by Xoch from ordered README packets. Edit packets, then rebuild. -->');
  for (const [displayPath, expanded] of resolved) {
    const body = fs.readFileSync(expanded, 'utf8').trim();
    lines.push('', `<!-- XOCH PACKET: ${displayPath} -->`, body, `<!-- END XOCH PACKET: ${displayPath} -->`);
  }
  const rendered = `${lines.join('\n')}\n`;

  if (dryRun) {
    console.log('README assembly valid');
    console.log(`Output: ${outputPath}`);
    console.log(`Title: ${title}`);
    resolved.forEach(([p], index) => console.log(`${index + 1}. ${p}`));
  } else if (stdoutMode) {
    process.stdout.write(rendered);
  } else {
    fs.mkdirSync(path.dirname(outputPath), { recursive: true });
    const temp = `${outputPath}.xoch-tmp`;
    fs.writeFileSync(temp, rendered);
    fs.renameSync(temp, outputPath);
    console.log(`README assembled: ${outputPath} (${resolved.length} packets)`);
  }
}

function main(argv) {
  const command = argv[0];
  if (command === '--help') {
    usage();
    return;
  }
  if (!command) {
    usage();
    process.exit(2);
  }
  if (command !== 'assemble') {
    usage();
    console.error(`Unknown command: ${command}`);
    process.exit(2);
  }
  assemble(argv.slice(1));
}

if (require.main === module) {
  main(process.argv.slice(2));
}

module.exports = { assemble, main };
